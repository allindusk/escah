# 按 key 长度降序执行：整句 > 复合词 > 道具名 > 通用短词，
# 使更长（更具体）的替换总是先命中，彻底避免短词把长句拆散导致匹配失败。
_JA2ZH_ORDERED = sorted(JA2ZH.items(), key=lambda kv: len(kv[0]), reverse=True)
_GENERIC_ORDERED = sorted(GENERIC.items(), key=lambda kv: len(kv[0]), reverse=True)


def patch(text: str) -> str:
    for ja, zh in _JA2ZH_ORDERED:
        if ja in text:
            text = text.replace(ja, zh)
    for pat, repl in REGEX_RULES:
        text = re.sub(pat, repl, text)
    for ja, zh in _GENERIC_ORDERED:
        if ja in text:
            text = text.replace(ja, zh)
    return text


# 统计残留日文（平假名 + 片假名）字符数，用于判断还需补哪些词
_KANA = re.compile(r"[぀-ゟ゠-ヿ]")


def residual_kana(text: str) -> int:
    return len(_KANA.findall(text))


# 受保护页：原始即为真译文（非 mock），不要被本工具从 ja 重新生成而覆盖。
# 仅顶层 4 页当初无 mock 标记；所有 369 个角色页原本皆是 mock，可安全重生成。
PROTECTED: set[str] = {
    "prereg-bonus.html",
    "daily-quest.html",
    "tips.html",
    "bedroom-scenes.html",
}


def main() -> int:
    # 除受保护页外，全部从 ja 源用词表重新生成（幂等：词表增长后重跑即应用新译文）。
    targets: list[Path] = []
    skipped = 0
    for ja_file in sorted(JA_DIR.rglob("*.html")):
        rel = str(ja_file.relative_to(JA_DIR))
        if rel in PROTECTED:
            skipped += 1
            continue
        targets.append(ja_file)

    if not targets:
        print("没有待处理的页面。")
        return 0

    total = 0
    for ja_file in targets:
        text = ja_file.read_text(encoding="utf-8")
        out = patch(text)
        zh_file = ZH_DIR / ja_file.relative_to(JA_DIR)
        zh_file.parent.mkdir(parents=True, exist_ok=True)
        zh_file.write_text(out, encoding="utf-8")
        k = residual_kana(out)
        total += k
        flag = "  <-- 仍有日文" if k else ""
        print(f"{zh_file.relative_to(ZH_DIR)}\t残留日文 {k}{flag}")

    print(f"\n跳过受保护页 {skipped} 页；本次重新生成 {len(targets)} 页，残留日文合计 {total} 字符。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
